#!/usr/bin/env python3
"""Generate NCQuickhacks_weaponmods.yaml - my quickhacks as ranged weapon mods
for "Quickhack Weapon Mods" (Nexus 24568).

No new redscript. That mod's effectorClassName only selects an upload-CHANCE
profile (each class just overrides SetMaxUploadChance); the hack that actually
fires comes from objectAction. So each of my mods borrows a vanilla-hack chance
profile and points objectAction at my own QuickHack record.

Quality Base is deliberately absent: the reference records list {quality: Base}
but no ...ApplyEffectorBase class exists in that mod, so a Base instance would
name a class that isn't there. Common..Legendary only.
"""
import io, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "r6", "tweaks", "NCQuickhacks",
                   "NCQuickhacks_weaponmods.yaml")

# (my hack, chance profile to borrow, vanilla iconPath)
HACKS = [
    ("SmartLinkScramble",    "WeaponGlitch",        "quickhack_wpn_malfunction"),
    ("ReflexJammer",         "CyberwareMalfunction", "quickhack_cw_malfunction"),
    ("OpticOverwrite",       "RebootOptics",        "quickhack_optics_malfunction"),
    ("PhantomOverlay",       "Contagion",           "program_generic"),
    ("MotorCortexInversion", "CrippleMovement",     "quickhack_locomo_malfunction"),
    ("AdrenalineOverdose",   "SynapseBurnout",      "quickhack_brainmelt"),
    ("CryptoSiphon",         "ShortCircuit",        "program_generic"),
]

HEAD = """\
# NCQuickhacks as ranged weapon mods.
#
# OPTIONAL. Requires "Quickhack Weapon Mods" (Nexus 24568) - every record here
# $bases or names something that mod defines. install.sh only copies this file
# when that mod is present; without it TweakXL would log unresolved bases.
#
# GENERATED by loc/build_weaponmods.py - edit that, not this.

"""

BLOCK = """\
Items.NCQ_Ranged{hack}Mod_$(quality):
  $instances:
    - {{quality: Common}}
    - {{quality: Uncommon}}
    - {{quality: Rare}}
    - {{quality: Epic}}
    - {{quality: Legendary}}
  $base: Items.RangedMod3_Mod_$(quality)
  iconPath: {icon}
  displayName: NCQ_WM_{hack}_name
  OnAttach:
    - $type: gamedataGameplayLogicPackage_Record
      effectors:
        - $type: gamedataEffector_Record
          $base: Items.RangedQuickhackModEffector
          objectAction:
              $type: gamedataObjectAction_Record
              $base: QuickHack.NCQ_{hack}Hack
              activationTime:
                - !append-once Items.QuickhackWeaponModUploadTimeMultiplier
          effectorClassName: Ranged{profile}ApplyEffector$(quality)
        - $type: gamedataEffector_Record
          $base: Items.RangedQuickhackModEffectorBoss
          objectAction:
              $type: gamedataObjectAction_Record
              $base: QuickHack.NCQ_{hack}Hack
              activationTime:
                - !append-once Items.QuickhackWeaponModUploadTimeMultiplier
          effectorClassName: Ranged{profile}ApplyEffectorBoss$(quality)
      stats:
        - $type: gamedataConstantStatModifier_Record
          $base: Items.AdvancedSelfIceRare_inline5
      UIData:
        $type: gamedataGameplayLogicPackageUIData_Record
        localizedDescription: NCQ_WM_{hack}_desc
  statModifiers: []
  quality: Quality.$(quality)
  tags:
    - !append-once $(quality)
    - !append-once Retrievable
    - !append-once NCQ_Ranged{hack}Mod
    - !remove RangedMod3

"""


def main():
    parts = [HEAD]
    for hack, profile, icon in HACKS:
        parts.append(BLOCK.format(hack=hack, profile=profile, icon=icon))

    # Stock them at the same vendors that carry the programs themselves.
    vendors = ["cz_con_netrunner_01", "cz_stadium_netrunner_01",
               "hey_rey_netrunner_01", "wat_kab_netrunner_01",
               "wat_lch_netrunner_01", "wbr_jpn_netrunner_01",
               "wbr_jpn_netrunner_02", "BlackMarketer_HUB"]
    for v in vendors:
        parts.append(f"Vendors.{v}:\n  itemStock:\n")
        for hack, _, _ in HACKS:
            parts.append(
                f"    - !append\n"
                f"      item: Items.NCQ_Ranged{hack}Mod_Rare\n"
                f"      quantity:\n"
                f"        - !append Vendors.Always_Present\n")
        parts.append("\n")

    io.open(OUT, "w", encoding="utf-8").write("".join(parts))
    print(f"wrote {os.path.basename(OUT)}: {len(HACKS)} weapon mods "
          f"x 5 qualities, stocked at {len(vendors)} vendors")


if __name__ == "__main__":
    main()
